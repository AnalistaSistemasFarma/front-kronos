import { oneDriveRoot } from '@/lib/onedrive/root';
import { getServerSession } from 'next-auth';
import { NextResponse } from 'next/server';
import { authOptions } from '../../auth/[...nextauth]/route';
import { useGetMicrosoftToken as getMicrosoftToken } from '@/components/microsoft-365/useGetMicrosoftToken';
import { listOneDriveFolderFiles } from '@/lib/onedrive/graphFolderUpload';
import { sql, withMssqlPool } from '@/lib/mssqlPool';

const STORAGE_PATHS = new Set(['SG', 'MA']);
const ENTITY_TYPES = new Set(['Request', 'Ticket']);

/**
 * Lista adjuntos de una solicitud en OneDrive (mismo token/ruta que upload).
 *
 * GET ?requestId=&storagePath=SG&entityType=Request
 */
export async function GET(req: Request) {
  try {
    const session = await getServerSession(authOptions);
    if (!session?.user) {
      return NextResponse.json({ error: 'No autorizado' }, { status: 401 });
    }

    const { searchParams } = new URL(req.url);
    const requestId = Number(searchParams.get('requestId') || searchParams.get('id'));
    const storagePath = String(searchParams.get('storagePath') || 'SG').trim() || 'SG';
    const entityType = String(searchParams.get('entityType') || 'Request').trim() || 'Request';

    if (!Number.isInteger(requestId) || requestId <= 0) {
      return NextResponse.json({ error: 'requestId inválido' }, { status: 400 });
    }
    // Solo las carpetas de adjuntos de SynerLink (no cualquier ruta de OneDrive).
    if (!STORAGE_PATHS.has(storagePath) || !ENTITY_TYPES.has(entityType)) {
      return NextResponse.json({ error: 'Carpeta no válida' }, { status: 400 });
    }

    const token = await getMicrosoftToken();
    if (!token) {
      return NextResponse.json({ error: 'No se pudo obtener token de OneDrive' }, { status: 502 });
    }

    const folderName = `${entityType}-${requestId}`;
    const files = await listOneDriveFolderFiles(token, [
      oneDriveRoot(),
      'TEC',
      storagePath,
      folderName,
    ]);

    console.log(
      `[list-attachments] request=${requestId} folder=${folderName} count=${files.length} names=${files.map((f) => f.name).join(' | ') || '(vacío)'}`
    );

    const marks = entityType === 'Request' ? await autogeneratedMarks(requestId) : new Map<string, Autogenerated>();

    return NextResponse.json(
      {
        ok: true,
        folder: `${oneDriveRoot()}/TEC/${storagePath}/${folderName}`,
        files: marks.size ? files.map((f) => (marks.has(String(f.id)) ? { ...f, autogenerated: marks.get(String(f.id)) } : f)) : files,
      },
      {
        headers: {
          'Cache-Control': 'no-store, max-age=0',
        },
      }
    );
  } catch (err) {
    const message = err instanceof Error ? err.message : 'Error interno';
    console.error('[list-attachments]', err);
    return NextResponse.json({ error: message }, { status: 500 });
  }
}

interface Autogenerated {
  version: number;
  sourceLabel: string | null;
  generatedBy: string | null;
  generatedAt: string | null;
  taskName: string | null;
}

/**
 * Archivos que generó una tarea «Plantilla de documento» (dbo.request_generated_document, emitidos):
 * id de OneDrive (PDF o Word) → datos para el distintivo «Autogenerado». Si falla, la lista sigue igual.
 */
async function autogeneratedMarks(requestId: number): Promise<Map<string, Autogenerated>> {
  const out = new Map<string, Autogenerated>();
  try {
    const rows = await withMssqlPool(async (pool) => {
      const r = await pool.request().input('req', sql.Int, requestId).query(`
        SELECT d.pdf_item_id, d.docx_item_id, d.version, d.source_label, d.generated_by, d.generated_at, tpc.task
        FROM dbo.request_generated_document d
        LEFT JOIN task_process_category tpc ON tpc.id = d.id_task
        WHERE d.id_request_general = @req AND d.status = N'emitido';`);
      return r.recordset;
    });
    for (const row of rows) {
      const mark: Autogenerated = {
        version: Number(row.version),
        sourceLabel: row.source_label ?? null,
        generatedBy: row.generated_by ?? null,
        generatedAt: row.generated_at ? new Date(row.generated_at).toISOString() : null,
        taskName: row.task ?? null,
      };
      if (row.pdf_item_id) out.set(String(row.pdf_item_id), mark);
      if (row.docx_item_id) out.set(String(row.docx_item_id), mark);
    }
  } catch (e) {
    console.warn('[list-attachments] no se pudieron leer los documentos autogenerados', e);
  }
  return out;
}
