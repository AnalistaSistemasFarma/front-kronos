'use client';

import { Badge, Tooltip } from '@mantine/core';

/** Datos de un adjunto generado por una tarea «Plantilla de documento» (list-attachments). */
export interface AutogeneratedInfo {
  version: number;
  sourceLabel?: string | null;
  generatedBy?: string | null;
  generatedAt?: string | null;
  taskName?: string | null;
}

const fmt = (iso?: string | null) => {
  if (!iso) return null;
  const d = new Date(iso);
  return Number.isNaN(d.getTime()) ? iso : d.toLocaleString('es-CO', { dateStyle: 'short', timeStyle: 'short' });
};

/** Distintivo «Autogenerado» junto al nombre del adjunto. No muestra nada si el archivo no es autogenerado. */
export function AutogeneratedBadge({ info }: { info?: AutogeneratedInfo | null }) {
  if (!info) return null;
  const label = [
    `Generado por la tarea ${info.taskName ?? 'Plantilla de documento'}`,
    `v${info.version}`,
    fmt(info.generatedAt),
    info.generatedBy,
  ]
    .filter(Boolean)
    .join(' · ');
  return (
    <Tooltip label={label} withArrow multiline maw={360}>
      <Badge size='xs' variant='light' color='violet' mt={2} styles={{ root: { textTransform: 'none' } }}>
        Autogenerado
      </Badge>
    </Tooltip>
  );
}
